  // ── Cap hours at realistic team capacity ──────────────────────────────────
  const teamCapacity       = getTeamCapacity(auditContext?.teamSize)
  const maxPerOpportunity  = Math.floor(teamCapacity * 0.3)
  const maxBelievableSaved = Math.floor(teamCapacity * 0.4)

