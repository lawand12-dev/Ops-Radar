function fmtMoney(n: number): string {
  if (n >= 1_000_000) return `$${(n / 1_000_000).toFixed(1)}M`
  if (n >= 1000)      return `$${(n / 1000).toFixed(0)}K`
  return `$${n.toLocaleString()}`
}

function fmtMoneyExact(n: number): string {
  return `$${Math.round(n).toLocaleString()}`
}

function getAnnualWasteValue(audit?: AuditResult | null): number | null {
  const value = audit?.labor_arbitrage_breakdown?.annual_labor_waste ?? audit?.estimated_annual_waste ?? null
  return typeof value === 'number' && Number.isFinite(value) ? value : null
}

function syncAnnualWasteCopy(text: string | undefined, annualWaste: number | null): string {
  if (!text || annualWaste == null) return text ?? ''

  const amount = fmtMoneyExact(annualWaste)

  return text
    .replace(
      /(\$\s?\d[\d,]*(?:\.\d+)?\s*(?:[KkMm])?)(\s*(?:annually|a year|per year|\/year|yearly))/gi,
      (_match, _dollarMatch, trailing) => `${amount}${trailing}`,
    )
    .replace(
      /((?:annual|annually|yearly|per year|a year|\/year)[^$]{0,18})(\$\s?\d[\d,]*(?:\.\d+)?\s*(?:[KkMm])?)/gi,
      (_match, leading) => `${leading}${amount}`,
    )
}

function splitCommaList(value?: string): string[] {
  if (!value) return []
  return value
    .split(',')
    .map((item) => item.trim())
    .filter(Boolean)
}

function splitSignalList(value?: string): string[] {
  if (!value) return []
  return value
    .split('|')
    .map((item) => item.trim())
    .filter(Boolean)
}

function uniqueStrings(items: string[]): string[] {
  return [...new Set(items.filter(Boolean))]
}

function parseWebsiteEvidence(value?: string): WebsiteEvidenceCard[] {
  if (!value) return []

  try {
    const parsed = JSON.parse(value) as unknown
    if (!Array.isArray(parsed)) return []

    return parsed
      .map((item) => {
        if (!item || typeof item !== 'object' || Array.isArray(item)) return null
        const record = item as Record<string, unknown>
        const label = typeof record.label === 'string' ? record.label.trim() : ''
        const detail = typeof record.detail === 'string' ? record.detail.trim() : ''
        const sourceLabel = typeof record.sourceLabel === 'string' ? record.sourceLabel.trim() : ''
        const sourcePath = typeof record.sourcePath === 'string' ? record.sourcePath.trim() : ''

        if (!label || !detail || !sourceLabel || !sourcePath) return null

        return {
          label,
          detail,
          sourceLabel,
          sourcePath,
        }
      })
      .filter((item): item is WebsiteEvidenceCard => Boolean(item))
  } catch {
    return []
  }
}

