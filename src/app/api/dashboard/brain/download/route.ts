/**
 * GET /api/dashboard/brain/download (CP-27)
 *
 * Streams the customer's entire brain as a zip of markdown files.
 * Reads from the Postgres-backed brain store, renders each document as
 * a markdown file in its path, packages with JSZip, returns as a
 * download attachment.
 *
 * The customer-facing "your brain, exportable anytime" surface. Same
 * content the Sunday cron emails them — available on demand from the
 * dashboard.
 */

import { NextResponse } from 'next/server'
import JSZip from 'jszip'
import { getCurrentUserId } from '<npm>/lib/supabase-ssr'
import { loadBrainDocuments } from '<npm>/lib/brain/store'

export const dynamic = 'force-dynamic'
export const runtime = 'nodejs'
export const maxDuration = 60

export async function GET() {
  const userId = await getCurrentUserId()
  if (!userId) {
    return NextResponse.json({ error: 'unauthorized' }, { status: 401 })
  }

  const docs = await loadBrainDocuments({ userId })

  const zip = new JSZip()

  // README at the root explaining what's in the export
  zip.file(
    'README.md',
    buildReadme({ docCount: docs.length, generatedAt: new Date().toISOString() }),
  )

  for (const doc of docs) {
    zip.file(doc.path, doc.content)
  }

  const buffer = await zip.generateAsync({
    type: 'nodebuffer',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 },
  })

  const filename = `opsradar-brain-${new Date().toISOString().slice(0, 10)}.zip`

  return new NextResponse(buffer as unknown as BodyInit, {
    status: 200,
    headers: {
      'Content-Type': 'application/zip',
      'Content-Disposition': `attachment; filename="${filename}"`,
      'Cache-Control': 'no-store',
    },
  })
}

function buildReadme(input: { docCount: number; generatedAt: string }): string {
  return [
    '# OpsRadar Brain Export',
    '',
    `Generated: **${input.generatedAt}**`,
    `Total documents: **${input.docCount}**`,
    '',
    '## What\'s in this archive',
    '',
    'Every markdown file is a piece of your business brain — patterns the',
    'AI noticed, decisions you logged, weekly KPI summaries, your How We',
    'Work playbook, and more.',
    '',
    '## Why we let you download this',
    '',
    'Your brain belongs to you. Even if OpsRadar disappears tomorrow:',
    '',
    '1. Your tools (Stripe, HubSpot, etc.) still have your raw data.',
    '2. Your Notion workspace stays in your Notion account.',
    '3. You have this markdown snapshot — readable in any tool, forever.',
    '',
    'No lock-in. Take this zip and continue your business journal anywhere.',
    '',
    '---',
    '',
    `*Generated by OpsRadar · ${input.generatedAt}*`,
  ].join('\n')
}
